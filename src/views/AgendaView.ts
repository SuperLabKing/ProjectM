import { Component, getFrontMatterInfo, ItemView, MarkdownRenderer, Menu, setIcon, type WorkspaceLeaf } from 'obsidian'
import type PMPlugin from '#main'
import {
  AGENDA_SOURCE_FILTERS,
  formatDate,
  locale,
  Temporal,
  stripAutoGeneratedContent,
  t,
  tn,
  today
} from '@dotpm/core'
import { safeAsync } from '@dotpm/ui'
import { openAgendaItem } from '#ui/agendaNavigation'
import { agendaEntries, agendaWeekEntries, arrangeWeekSlots, type AgendaEntry, type AgendaItem } from './agendaEntries'

export const PM_AGENDA_VIEW_TYPE = 'pm-agenda'
const HOUR_HEIGHT = 50

function clockTime(minutes: number): string {
  return String(Math.floor(minutes / 60)).padStart(2, '0') + ':' + String(minutes % 60).padStart(2, '0')
}

export class AgendaView extends ItemView {
  private refreshTimer = 0
  private revision = 0
  private displayedDay = ''
  private clockTimer = 0
  private body!: HTMLElement
  private filterButton?: HTMLButtonElement
  private items?: AgendaItem[]
  private selected: 'today' | 'tomorrow' | 'upcoming' | 'week' = 'today'
  private sections?: ReturnType<typeof agendaEntries>
  private week?: ReturnType<typeof agendaWeekEntries>
  private overdueExpanded = false
  private rangeButtons = new Map<AgendaView['selected'], HTMLButtonElement>()
  private previewTimer = 0
  private preview?: { row: HTMLElement; element: HTMLElement; component: Component }

  constructor(
    leaf: WorkspaceLeaf,
    private plugin: PMPlugin
  ) {
    super(leaf)
  }

  getViewType(): string {
    return PM_AGENDA_VIEW_TYPE
  }

  getDisplayText(): string {
    return t('agenda.title')
  }

  getIcon(): string {
    return 'calendar-clock'
  }

  async onOpen(): Promise<void> {
    this.contentEl.addClass('pm-agenda')
    const ranges = this.contentEl.createDiv({
      cls: 'pm-agenda-ranges',
      attr: { role: 'group', 'aria-label': t('agenda.title') }
    })
    for (const [key, label] of [
      ['today', t('agenda.today')],
      ['tomorrow', t('agenda.tomorrow')],
      ['upcoming', t('agenda.upcoming')],
      ['week', t('agenda.weekView')]
    ] as const) {
      const button = ranges.createEl('button', {
        text: label,
        attr: { type: 'button', 'aria-pressed': String(key === this.selected) }
      })
      this.rangeButtons.set(key, button)
      this.registerDomEvent(button, 'click', () => {
        if (key === this.selected) return
        this.selected = key
        for (const [range, option] of this.rangeButtons) option.setAttribute('aria-pressed', String(range === key))
        this.renderSections()
      })
    }
    const filter = ranges.createEl('button', {
      cls: 'pm-agenda-source-filter',
      attr: { type: 'button', 'aria-haspopup': 'menu' }
    })
    setIcon(filter, 'list-filter')
    this.filterButton = filter
    this.updateSourceFilterButton()
    this.registerDomEvent(filter, 'click', () => this.openSourceMenu(filter))
    this.body = this.contentEl.createDiv('pm-agenda-body')
    this.registerDomEvent(this.contentEl, 'scroll', () => this.dismissPreview(), true)
    this.body.createEl('p', { cls: 'pm-agenda-empty', text: t('agenda.loading') })
    this.register(this.plugin.index.onChange(() => this.scheduleRefresh()))
    this.register(this.plugin.timedReminders.onSnoozeChanged(() => this.scheduleRefresh()))
    this.registerEvent(this.app.metadataCache.on('changed', () => this.scheduleRefresh()))
    this.registerEvent(this.app.metadataCache.on('resolved', () => this.scheduleRefresh()))
    this.registerEvent(this.app.vault.on('delete', () => this.scheduleRefresh()))
    this.registerEvent(this.app.vault.on('rename', () => this.scheduleRefresh()))
    const win = this.contentEl.ownerDocument.defaultView
    if (win) this.registerDomEvent(win, 'focus', () => this.updateClock())
    this.tickClock()
    await this.refresh()
  }

  async onClose(): Promise<void> {
    this.revision++
    this.dismissPreview()
    window.clearTimeout(this.refreshTimer)
    this.contentEl.ownerDocument.defaultView?.clearTimeout(this.clockTimer)
    this.rangeButtons.clear()
    this.filterButton = undefined
    this.items = undefined
    this.sections = undefined
    this.week = undefined
    this.contentEl.empty()
  }

  private tickClock(): void {
    this.updateClock()
    const win = this.contentEl.ownerDocument.defaultView
    if (win) this.clockTimer = win.setTimeout(() => this.tickClock(), 60_000 - (Date.now() % 60_000))
  }

  private updateClock(): void {
    const now = Temporal.Now.plainDateTimeISO()
    const day = now.toPlainDate().toString()
    if (this.displayedDay && this.displayedDay !== day) this.scheduleRefresh()
    const timeline = this.body.querySelector('.pm-agenda-timeline')
    if (!timeline) return
    const lane = [...timeline.querySelectorAll<HTMLElement>('.pm-agenda-time-lane')].find(
      (item) => item.dataset.day === day
    )
    timeline.querySelectorAll('.pm-agenda-now').forEach((line) => {
      if (line.parentElement !== lane) line.remove()
    })
    if (!lane) return
    const minutes = now.hour * 60 + now.minute
    const line =
      lane.querySelector<HTMLElement>('.pm-agenda-now') ??
      lane.createDiv({ cls: 'pm-agenda-now', attr: { role: 'img' } })
    line.style.insetBlockStart = (minutes * HOUR_HEIGHT) / 60 + 'px'
    line.setAttr('aria-label', t('agenda.now', { time: clockTime(minutes) }))
  }

  private scheduleRefresh(): void {
    this.revision++
    window.clearTimeout(this.refreshTimer)
    this.refreshTimer = window.setTimeout(
      safeAsync(() => this.refresh()),
      160
    )
  }

  private async refresh(): Promise<void> {
    const revision = ++this.revision
    const items = await this.plugin.agendaSource.load(() => revision === this.revision)
    if (revision !== this.revision) return
    this.items = items
    this.applySourceFilter()
  }

  private updateSourceFilterButton(): void {
    const filter = this.plugin.settings.agendaSourceFilter
    const name = t('agenda.sourceFilterCurrent', { source: t(`agenda.sourceFilter.${filter}`) })
    this.filterButton?.setAttr('aria-label', name)
    this.filterButton?.setAttr('title', name)
    this.filterButton?.toggleClass('is-filtered', filter !== 'all')
  }

  private openSourceMenu(button: HTMLButtonElement): void {
    const menu = new Menu()
    for (const filter of AGENDA_SOURCE_FILTERS) {
      menu.addItem((item) =>
        item
          .setTitle(t(`agenda.sourceFilter.${filter}`))
          .setChecked(this.plugin.settings.agendaSourceFilter === filter)
          .onClick(safeAsync(() => this.plugin.setAgendaSourceFilter(filter)))
      )
    }
    const bounds = button.getBoundingClientRect()
    menu.showAtPosition({ x: bounds.left, y: bounds.bottom + 4 }, button.ownerDocument)
  }

  applySourceFilter(): void {
    this.updateSourceFilterButton()
    if (!this.items) return
    const filter = this.plugin.settings.agendaSourceFilter
    const items =
      filter === 'all'
        ? this.items
        : this.items.filter((item) => (item.line !== undefined) === (filter === 'checklist'))
    const current = today()
    this.displayedDay = current.toString()
    this.sections = agendaEntries(items, current)
    this.week = agendaWeekEntries(items, current)
    this.renderSections()
  }

  private renderSections(focusMore = false): void {
    const sections = this.sections
    if (!sections) return
    this.dismissPreview()
    const weekScroll = this.body.querySelector<HTMLElement>('.pm-agenda-week-scroll')
    const scroll = weekScroll ? { left: weekScroll.scrollLeft, top: weekScroll.scrollTop } : undefined
    this.body.empty()
    this.contentEl.toggleClass('pm-agenda-show-week', this.selected === 'week')
    if (this.selected === 'today') {
      if (sections.overdue.length) this.renderOverdue(sections.overdue, focusMore)
      if (sections.today.length && sections.overdue.length) {
        this.body
          .createDiv({ cls: 'pm-agenda-section-heading' })
          .createEl('h3', { text: t('agenda.todayCount', { count: sections.today.length }) })
      }
      if (sections.today.length || !sections.overdue.length) this.renderList(this.body, sections.today)
      return
    }
    if (this.selected === 'week') {
      this.renderWeek(scroll)
      return
    }
    const tomorrow = today().add({ days: 1 }).toString()
    const items =
      this.selected === 'tomorrow' ? sections.upcoming.filter(({ day }) => day === tomorrow) : sections.upcoming
    this.renderList(this.body, items)
  }

  private renderWeek(scroll?: { left: number; top: number }): void {
    const week = this.week
    if (!week) return
    const region = this.body.createDiv({
      cls: 'pm-agenda-week-scroll',
      attr: { role: 'region', tabindex: '0', 'aria-label': t('agenda.weekView') }
    })
    const table = region.createEl('table', { cls: 'pm-agenda-week-table' })
    table.style.setProperty('--pm-agenda-hour-height', HOUR_HEIGHT + 'px')
    const head = table.createEl('thead')
    const heading = head.createEl('tr')
    heading.createEl('td')
    for (const { day } of week) {
      const cell = heading.createEl('th', { attr: { scope: 'col' } })
      if (day.toString() === this.displayedDay) cell.setAttribute('aria-current', 'date')
      cell.createSpan({ text: day.toLocaleString(locale(), { weekday: 'short' }) })
      cell.createEl('time', { text: day.month + '/' + day.day, attr: { datetime: day.toString() } })
    }
    const allDay = head.createEl('tr', { cls: 'pm-agenda-all-day' })
    allDay.createEl('th', { text: t('agenda.allDay'), attr: { scope: 'row' } })
    for (const { entries } of week) {
      const cell = allDay.createEl('td').createDiv('pm-agenda-all-day-items')
      for (const entry of entries) if (!entry.slot) this.renderEntry(cell, entry, '')
    }

    const timeline = table.createEl('tbody').createEl('tr', { cls: 'pm-agenda-timeline' })
    const hours = timeline.createEl('th', { cls: 'pm-agenda-hours', attr: { scope: 'row' } })
    for (let hour = 0; hour < 24; hour++) hours.createDiv({ text: clockTime(hour * 60) })
    let earliest = 9 * 60
    const slots = week.map(({ entries }) => arrangeWeekSlots(entries))
    const first = Math.min(...slots.flat().map(({ start }) => start))
    if (Number.isFinite(first)) earliest = first
    const lanes = week.map(({ date }) =>
      timeline.createEl('td').createDiv({ cls: 'pm-agenda-time-lane', attr: { 'data-day': date } })
    )
    for (const [index, day] of slots.entries()) {
      const lane = lanes[index]
      for (const slot of day) {
        const block = this.renderEntry(lane, slot.entry, clockTime(slot.start))
        const duration = slot.end === undefined ? undefined : slot.end - slot.start
        block.addClass('pm-agenda-timed-item')
        block.toggleAttribute('data-point', duration === undefined)
        block.toggleAttribute('data-short', duration !== undefined && duration < 35)
        block.toggleAttribute('data-compact', duration !== undefined && duration < 60)
        block.style.insetBlockStart = (slot.start / 60) * HOUR_HEIGHT + 'px'
        block.style.insetInlineStart = (slot.lane / slot.lanes) * 100 + '%'
        block.style.inlineSize = 100 / slot.lanes + '%'
        if (duration !== undefined) block.style.blockSize = (duration / 60) * HOUR_HEIGHT + 'px'
      }
    }
    this.updateClock()
    region.scrollTop = scroll?.top ?? Math.max(0, Math.floor(earliest / 60) - 1) * HOUR_HEIGHT
    region.scrollLeft = scroll?.left ?? 0
  }

  private renderOverdue(entries: AgendaEntry[], focusMore: boolean): void {
    const section = this.body.createEl('section', { cls: 'pm-agenda-overdue' })
    const header = section.createDiv({ cls: 'pm-agenda-section-heading' })
    header.createEl('h3', { text: t('agenda.overdueCount', { count: entries.length }) })
    if (entries.length > 2) {
      const button = header.createEl('button', {
        cls: 'pm-agenda-more',
        attr: { type: 'button', 'aria-expanded': String(this.overdueExpanded) }
      })
      button.createSpan({
        text: this.overdueExpanded ? t('agenda.showLess') : t('agenda.showRemaining', { count: entries.length - 2 })
      })
      setIcon(button.createSpan(), this.overdueExpanded ? 'chevron-up' : 'chevron-right')
      button.addEventListener('click', () => {
        this.overdueExpanded = !this.overdueExpanded
        this.renderSections(true)
      })
      if (focusMore) button.focus({ preventScroll: true })
    }
    this.renderList(section, this.overdueExpanded ? entries : entries.slice(0, 2))
  }

  private renderList(parent: HTMLElement, entries: AgendaEntry[]): void {
    if (!entries.length) parent.createEl('p', { cls: 'pm-agenda-empty', text: t('agenda.empty') })
    for (const entry of entries) this.renderEntry(parent, entry)
  }

  private renderEntry(section: HTMLElement, entry: AgendaEntry, timetableTime?: string): HTMLButtonElement {
    const { item, day, start, due, overdueDays } = entry
    const row = section.createEl('button', { cls: 'pm-agenda-row', attr: { type: 'button' } })
    if (timetableTime !== undefined) row.addClass('pm-agenda-week-item')
    if (overdueDays) row.setAttribute('data-overdue', '')
    const dot = row.createSpan({
      cls: 'pm-agenda-status-dot',
      attr: { 'data-status-tone': item.statusTone ?? 'other', 'aria-hidden': 'true' }
    })
    row.createSpan({ cls: 'pm-agenda-row-title', text: item.title })
    if (timetableTime === undefined) {
      const status = row.createSpan({ cls: 'pm-agenda-row-status', attr: { 'aria-hidden': 'true' } })
      status.append(dot, item.status)
    }
    const time = start?.time && due?.time ? `${start.time}~${due.time}` : (start?.time ?? due?.time)
    const date = day.slice(5).replace('-', '/')
    const short = overdueDays || this.selected === 'upcoming' ? date : (time ?? t(due ? 'agenda.due' : 'agenda.allDay'))
    const visibleTime = timetableTime ?? short
    if (visibleTime) row.createEl('time', { cls: 'pm-agenda-dates', text: visibleTime, attr: { datetime: day } })
    row.setAttribute('aria-label', [item.title, this.entryDetails(entry)].join(' · '))
    const schedule = () => {
      this.dismissPreview()
      const win = row.ownerDocument.defaultView
      if (!win) return
      this.previewTimer = win.setTimeout(
        safeAsync(() => this.openPreview(row, entry)),
        330
      )
    }
    row.addEventListener('pointerenter', (event) => {
      if (event.pointerType !== 'touch') schedule()
    })
    row.addEventListener('pointerleave', () => this.dismissPreview())
    row.addEventListener('focus', () => {
      if (row.matches(':focus-visible')) schedule()
    })
    row.addEventListener('blur', () => this.dismissPreview())
    row.addEventListener('keydown', (event) => {
      if (event.key === 'Escape') this.dismissPreview()
    })
    row.addEventListener(
      'click',
      safeAsync(async () => {
        this.dismissPreview()
        await openAgendaItem(this.plugin, item)
      })
    )
    return row
  }

  private entryDetails({ item, overdueDays }: AgendaEntry): string {
    const details = [item.source, item.status]
    for (const [label, date] of [
      [t('agenda.plan'), item.start],
      [t('agenda.due'), item.due]
    ] as const) {
      if (date) details.push([label, formatDate(date.day), date.time].filter(Boolean).join(' '))
    }
    if (overdueDays) details.push(tn('dates.overdueDays', overdueDays))
    const snoozes = this.plugin.timedReminders.snoozeCount(item.reminderId)
    if (snoozes) details.push(tn('agenda.snoozeCount', snoozes))
    return details.filter(Boolean).join(' · ')
  }

  private dismissPreview(): void {
    this.contentEl.ownerDocument.defaultView?.clearTimeout(this.previewTimer)
    if (!this.preview) return
    this.preview.row.removeAttribute('aria-describedby')
    this.preview.element.remove()
    this.removeChild(this.preview.component)
    this.preview = undefined
  }

  private async openPreview(row: HTMLElement, entry: AgendaEntry): Promise<void> {
    const { item } = entry
    const win = row.ownerDocument.defaultView
    if (!win || !row.parentElement || !row.isConnected) return
    const component = this.addChild(new Component())
    const element = row.parentElement.createDiv({
      cls: 'pm-agenda-preview',
      attr: { popover: 'manual', role: 'tooltip', id: 'pm-agenda-entry-preview' }
    })
    const preview = { row, element, component }
    this.preview = preview
    element.createDiv({ cls: 'pm-agenda-preview-title', text: item.title })
    element.createDiv({ cls: 'pm-agenda-preview-meta', text: this.entryDetails(entry) })
    const body = element.createDiv({ cls: 'pm-agenda-preview-body markdown-rendered' })
    try {
      const { markdown, path } = await this.previewContent(item)
      if (this.preview !== preview) return
      if (markdown) await MarkdownRenderer.render(this.app, markdown, body, path, component)
      else body.setText(t('agenda.noDescription'))
    } catch {
      body.setText(t('agenda.previewUnavailable'))
    }
    if (this.preview !== preview || !row.isConnected) return
    body.querySelectorAll('input').forEach((input) => {
      input.disabled = true
    })
    body.querySelectorAll('a, button, [tabindex]').forEach((link) => link.setAttribute('tabindex', '-1'))
    const rect = row.getBoundingClientRect()
    element.showPopover()
    const width = element.offsetWidth
    const height = element.offsetHeight
    element.style.left = `${Math.max(8, Math.min(rect.left + 8, win.innerWidth - width - 8))}px`
    const top = rect.bottom + height + 14 < win.innerHeight ? rect.bottom + 6 : rect.top - height - 6
    element.style.top = `${Math.max(8, top)}px`
    row.setAttribute('aria-describedby', element.id)
  }

  private async previewContent(item: AgendaItem): Promise<{ markdown: string; path: string }> {
    const id = item.reminderId?.startsWith('task:') ? item.reminderId.slice(5) : undefined
    const path = (id && this.plugin.index.task(id)?.path) || item.path
    const file = this.app.vault.getFileByPath(path)
    if (!file) throw new Error('Missing agenda source')
    const text = await this.app.vault.cachedRead(file)
    if (item.line === undefined) {
      return { markdown: stripAutoGeneratedContent(text.slice(getFrontMatterInfo(text).contentStart)).trim(), path }
    }
    const line = item.reminderId ? await this.plugin.agendaSource.findChecklistLine(file, item.reminderId) : item.line
    if (line === undefined) throw new Error('Missing checklist item')
    const lines = text.split(/\r?\n/)
    const first = lines[line]
    if (first === undefined) throw new Error('Missing checklist line')
    const indent = first.match(/^\s*/)?.[0].length ?? 0
    const excerpt = [first]
    for (const child of lines.slice(line + 1, line + 8)) {
      const leading = child.match(/^\s*/)?.[0].length ?? 0
      if (!child.trim() || leading <= indent) break
      excerpt.push(child)
    }
    return { markdown: excerpt.map((entry) => entry.slice(indent)).join('\n'), path }
  }
}

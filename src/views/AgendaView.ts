import { Component, getFrontMatterInfo, ItemView, MarkdownRenderer, setTooltip, type WorkspaceLeaf } from 'obsidian'
import type PMPlugin from '#main'
import { formatDate, stripAutoGeneratedContent, t, tn, today } from '@dotpm/core'
import { safeAsync } from '@dotpm/ui'
import { openAgendaItem } from '#ui/agendaNavigation'
import { agendaEntries, type AgendaEntry, type AgendaItem } from './agendaEntries'

export const PM_AGENDA_VIEW_TYPE = 'pm-agenda'

export class AgendaView extends ItemView {
  private refreshTimer = 0
  private revision = 0
  private displayedDay = ''
  private body!: HTMLElement
  private previewTimer = 0
  private preview?: { row: HTMLElement; element: HTMLElement; component: Component }

  constructor(
    leaf: WorkspaceLeaf,
    private plugin: PMPlugin
  ) {
    super(leaf)
  }

  getViewType(): string {
    return PM_AGENDA_VIEW_TYPE
  }

  getDisplayText(): string {
    return t('agenda.title')
  }

  getIcon(): string {
    return 'calendar-clock'
  }

  async onOpen(): Promise<void> {
    this.contentEl.addClass('pm-agenda')
    this.contentEl.createEl('h2', { text: t('agenda.title') })
    this.body = this.contentEl.createDiv()
    this.registerDomEvent(this.contentEl, 'scroll', () => this.dismissPreview(), true)
    this.body.createEl('p', { cls: 'pm-agenda-empty', text: t('agenda.loading') })
    this.register(this.plugin.index.onChange(() => this.scheduleRefresh()))
    this.register(this.plugin.timedReminders.onSnoozeChanged(() => this.scheduleRefresh()))
    this.registerEvent(this.app.metadataCache.on('changed', () => this.scheduleRefresh()))
    this.registerEvent(this.app.metadataCache.on('resolved', () => this.scheduleRefresh()))
    this.registerEvent(this.app.vault.on('delete', () => this.scheduleRefresh()))
    this.registerEvent(this.app.vault.on('rename', () => this.scheduleRefresh()))
    this.registerInterval(
      window.setInterval(() => {
        if (this.displayedDay !== today().toString()) this.scheduleRefresh()
      }, 60_000)
    )
    await this.refresh()
  }

  async onClose(): Promise<void> {
    this.revision++
    this.dismissPreview()
    window.clearTimeout(this.refreshTimer)
    this.contentEl.empty()
  }

  private scheduleRefresh(): void {
    this.revision++
    window.clearTimeout(this.refreshTimer)
    this.refreshTimer = window.setTimeout(
      safeAsync(() => this.refresh()),
      160
    )
  }

  private async refresh(): Promise<void> {
    const revision = ++this.revision
    const items = await this.plugin.agendaSource.load(() => revision === this.revision)
    if (revision !== this.revision) return
    const current = today()
    this.displayedDay = current.toString()
    const sections = agendaEntries(items, current)
    this.dismissPreview()
    this.body.empty()
    for (const [key, title] of [
      ['overdue', t('agenda.overdue')],
      ['today', t('agenda.today')],
      ['upcoming', t('agenda.upcoming')]
    ] as const) {
      const section = this.body.createEl('section', { cls: 'pm-agenda-section', attr: { 'data-section': key } })
      section.createEl('h3', { text: title })
      if (!sections[key].length) section.createEl('p', { cls: 'pm-agenda-empty', text: t('agenda.empty') })
      for (const entry of sections[key]) this.renderEntry(section, entry)
    }
  }

  private renderEntry(section: HTMLElement, { item, day, start, due, overdueDays }: AgendaEntry): void {
    const row = section.createEl('button', { cls: 'pm-agenda-row', attr: { type: 'button' } })
    const heading = row.createSpan('pm-agenda-row-heading')
    heading.createSpan({ cls: 'pm-agenda-row-title', text: item.title })
    const meta = heading.createSpan('pm-agenda-meta')
    meta.createSpan({ cls: 'pm-agenda-source', text: item.source })
    meta.createSpan({
      cls: 'pm-agenda-status',
      text: item.status,
      attr: { 'data-status-tone': item.statusTone ?? 'other' }
    })
    const snoozes = this.plugin.timedReminders.snoozeCount(item.reminderId)
    if (snoozes) meta.createSpan({ cls: 'pm-agenda-snooze-count', text: tn('agenda.snoozeCount', snoozes) })
    const dates = row.createSpan('pm-agenda-dates')
    if (overdueDays) {
      const label = tn('dates.overdueDays', overdueDays)
      dates.createSpan({ cls: 'pm-agenda-late-dot', attr: { role: 'img', 'aria-label': label } })
      setTooltip(dates, label)
    }
    dates.createSpan({ cls: 'pm-agenda-date-label', text: start ? t('agenda.plan') : t('agenda.due') })
    dates.createEl('time', { text: formatDate(day), attr: { datetime: day } })
    if (start?.time && due?.time) {
      dates.createSpan({ cls: 'pm-agenda-date-time', text: `${start.time}~${due.time}` })
    } else if (start?.time) {
      dates.createSpan({ cls: 'pm-agenda-date-time', text: start.time })
    } else if (due?.time) {
      dates.createSpan({ cls: 'pm-agenda-date-time', text: start ? `${t('agenda.due')} ${due.time}` : due.time })
    }
    const schedule = () => {
      this.dismissPreview()
      const win = row.ownerDocument.defaultView
      if (!win) return
      this.previewTimer = win.setTimeout(
        safeAsync(() => this.openPreview(row, item)),
        330
      )
    }
    row.addEventListener('pointerenter', (event) => {
      if (event.pointerType !== 'touch') schedule()
    })
    row.addEventListener('pointerleave', () => this.dismissPreview())
    row.addEventListener('focus', () => {
      if (row.matches(':focus-visible')) schedule()
    })
    row.addEventListener('blur', () => this.dismissPreview())
    row.addEventListener('keydown', (event) => {
      if (event.key === 'Escape') this.dismissPreview()
    })
    row.addEventListener(
      'click',
      safeAsync(async () => {
        this.dismissPreview()
        await openAgendaItem(this.plugin, item)
      })
    )
  }

  private dismissPreview(): void {
    this.contentEl.ownerDocument.defaultView?.clearTimeout(this.previewTimer)
    if (!this.preview) return
    this.preview.row.removeAttribute('aria-describedby')
    this.preview.element.remove()
    this.removeChild(this.preview.component)
    this.preview = undefined
  }

  private async openPreview(row: HTMLElement, item: AgendaItem): Promise<void> {
    const win = row.ownerDocument.defaultView
    if (!win || !row.parentElement || !row.isConnected) return
    const component = this.addChild(new Component())
    const element = row.parentElement.createDiv({
      cls: 'pm-agenda-preview',
      attr: { popover: 'manual', role: 'tooltip', id: 'pm-agenda-entry-preview' }
    })
    const preview = { row, element, component }
    this.preview = preview
    element.createDiv({ cls: 'pm-agenda-preview-title', text: item.title })
    const body = element.createDiv({ cls: 'pm-agenda-preview-body markdown-rendered' })
    try {
      const { markdown, path } = await this.previewContent(item)
      if (this.preview !== preview) return
      if (markdown) await MarkdownRenderer.render(this.app, markdown, body, path, component)
      else body.setText(t('agenda.noDescription'))
    } catch {
      body.setText(t('agenda.previewUnavailable'))
    }
    if (this.preview !== preview || !row.isConnected) return
    body.querySelectorAll('input').forEach((input) => {
      input.disabled = true
    })
    body.querySelectorAll('a, button, [tabindex]').forEach((link) => link.setAttribute('tabindex', '-1'))
    const rect = row.getBoundingClientRect()
    element.showPopover()
    const width = element.offsetWidth
    const height = element.offsetHeight
    element.style.left = `${Math.max(8, Math.min(rect.left + 8, win.innerWidth - width - 8))}px`
    const top = rect.bottom + height + 14 < win.innerHeight ? rect.bottom + 6 : rect.top - height - 6
    element.style.top = `${Math.max(8, top)}px`
    row.setAttribute('aria-describedby', element.id)
  }

  private async previewContent(item: AgendaItem): Promise<{ markdown: string; path: string }> {
    const id = item.reminderId?.startsWith('task:') ? item.reminderId.slice(5) : undefined
    const path = (id && this.plugin.index.task(id)?.path) || item.path
    const file = this.app.vault.getFileByPath(path)
    if (!file) throw new Error('Missing agenda source')
    const text = await this.app.vault.cachedRead(file)
    if (item.line === undefined) {
      return { markdown: stripAutoGeneratedContent(text.slice(getFrontMatterInfo(text).contentStart)).trim(), path }
    }
    const line = item.reminderId ? await this.plugin.agendaSource.findChecklistLine(file, item.reminderId) : item.line
    if (line === undefined) throw new Error('Missing checklist item')
    const lines = text.split(/\r?\n/)
    const first = lines[line]
    if (first === undefined) throw new Error('Missing checklist line')
    const indent = first.match(/^\s*/)?.[0].length ?? 0
    const excerpt = [first]
    for (const child of lines.slice(line + 1, line + 8)) {
      const leading = child.match(/^\s*/)?.[0].length ?? 0
      if (!child.trim() || leading <= indent) break
      excerpt.push(child)
    }
    return { markdown: excerpt.map((entry) => entry.slice(indent)).join('\n'), path }
  }
}
